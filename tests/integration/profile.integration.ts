import { randomUUID } from "node:crypto";
import { afterAll, afterEach, beforeAll, beforeEach, expect, it, vi } from "vitest";
import { TEST_DATABASE_URL } from "../support/local-database";

const auth = vi.hoisted(() => ({ getUser: vi.fn() }));
vi.mock("server-only", () => ({}));
vi.mock("@/lib/supabase/server", () => ({
  createClient: async () => ({ auth: { getUser: auth.getUser } }),
}));
vi.mock("next/cache", () => ({ revalidatePath: vi.fn() }));
vi.mock("next/navigation", () => ({
  redirect: (path: string) => { throw new Error(`redirect:${path}`); },
}));

// These are the actual application functions and Prisma connection, not DB mocks.
import { prisma } from "@/lib/db";
import { ensureCurrentUserProfile } from "@/lib/ensure-profile";
import { getCurrentProfile } from "@/lib/profile";
import { saveProfile } from "@/app/dashboard/actions";
import { saveCareerPreferences } from "@/app/dashboard/preferences-actions";

let identities: string[] = [];
let accountA: string;
let accountB: string;
let verifiedDatabase = false;

function signIn(id: string) {
  auth.getUser.mockResolvedValue({ data: { user: { id } }, error: null });
}

function form(name: string) {
  const data = new FormData();
  data.set("displayName", name);
  data.set("headline", "Test developer");
  data.set("careerGoals", "Integration test fixture");
  return data;
}

beforeAll(async () => {
  expect(process.env.DATABASE_URL).toBe(TEST_DATABASE_URL);
  const rows = await prisma.$queryRaw<Array<{ name: string; role: string }>>`
    SELECT current_database() AS name, current_user AS role
  `;
  expect(rows).toEqual([{ name: "careeros_test", role: "careeros_test" }]);
  verifiedDatabase = true;
});

beforeEach(async () => {
  if (!verifiedDatabase) throw new Error("Local test database verification failed.");
  accountA = randomUUID();
  accountB = randomUUID();
  identities = [accountA, accountB];
  for (const id of identities) {
    signIn(id);
    await ensureCurrentUserProfile();
  }
  signIn(accountA);
});

afterEach(async () => {
  // Delete only identities generated by this test; FK cascade removes their profiles.
  if (verifiedDatabase && identities.length) {
    await prisma.user.deleteMany({ where: { supabaseAuthId: { in: identities } } });
  }
  identities = [];
});

afterAll(async () => { await prisma.$disconnect(); });

it("starts existing-style profiles with empty preferences", async () => {
  expect(await getCurrentProfile()).toMatchObject({ targetRoles: [], industries: [], workArrangements: [], employmentTypes: [] });
});

it("persists and clears preferences without altering either account's basic profile", async () => {
  await saveProfile({}, form("Account A original"));
  const data = new FormData();
  data.set("targetRoles", "Developer\nMechanical Engineer");
  data.set("industries", "Manufacturing");
  data.append("workArrangements", "hybrid");
  data.append("employmentTypes", "contract");
  const other = await prisma.careerProfile.findFirstOrThrow({ where: { user: { supabaseAuthId: accountB } } });
  data.set("userId", other.userId); data.set("id", other.id); data.set("supabaseAuthId", accountB);
  expect((await saveCareerPreferences({}, data)).message).toBe("Career preferences saved.");
  expect(await getCurrentProfile()).toMatchObject({ displayName: "Account A original", careerGoals: "Integration test fixture", targetRoles: ["Developer", "Mechanical Engineer"], industries: ["Manufacturing"], workArrangements: ["hybrid"], employmentTypes: ["contract"] });
  expect(await prisma.careerProfile.findUnique({ where: { id: other.id } })).toEqual(other);
  await saveProfile({}, form("Basic edit"));
  expect((await getCurrentProfile())?.targetRoles).toEqual(["Developer", "Mechanical Engineer"]);
  data.set("targetRoles", ""); data.set("industries", ""); data.delete("workArrangements"); data.delete("employmentTypes");
  await saveCareerPreferences({}, data);
  expect(await getCurrentProfile()).toMatchObject({ displayName: "Basic edit", targetRoles: [], industries: [], workArrangements: [], employmentTypes: [] });
});

it("provisions exactly one user and profile when requests overlap", async () => {
  const id = randomUUID();
  identities.push(id);
  signIn(id);
  const results = await Promise.all(Array.from({ length: 4 }, () => ensureCurrentUserProfile()));
  expect(new Set(results).size).toBe(1);
  expect(await prisma.user.count({ where: { supabaseAuthId: id } })).toBe(1);
  expect(await prisma.careerProfile.count({ where: { user: { supabaseAuthId: id } } })).toBe(1);
});

it("persists distinct profiles and reads only the authenticated account", async () => {
  expect(await saveProfile({}, form("Account A"))).toEqual({ message: "Profile saved." });
  signIn(accountB);
  expect(await saveProfile({}, form("Account B"))).toEqual({ message: "Profile saved." });
  expect((await getCurrentProfile())?.displayName).toBe("Account B");
  signIn(accountA);
  expect((await getCurrentProfile())?.displayName).toBe("Account A");
});

it("ignores forged ownership fields and leaves the other profile unchanged", async () => {
  const target = await prisma.careerProfile.findFirstOrThrow({
    where: { user: { supabaseAuthId: accountB } },
  });
  const forged = form("Account A changed");
  forged.set("id", target.id);
  forged.set("profileId", target.id);
  forged.set("userId", target.userId);
  forged.set("supabaseAuthId", accountB);
  expect(await saveProfile({}, forged)).toEqual({ message: "Profile saved." });
  expect(await prisma.careerProfile.findUnique({ where: { id: target.id } })).toEqual(target);
  expect((await getCurrentProfile())?.displayName).toBe("Account A changed");
});

it("rejects unauthenticated operations without changing saved rows", async () => {
  const before = await prisma.careerProfile.findMany({
    where: { user: { supabaseAuthId: { in: identities } } }, orderBy: { id: "asc" },
  });
  auth.getUser.mockResolvedValue({ data: { user: null }, error: null });
  expect((await saveProfile({}, form("Unauthorized"))).error).toBeTruthy();
  await expect(getCurrentProfile()).rejects.toThrow("redirect:/login");
  await expect(ensureCurrentUserProfile()).rejects.toThrow("Authentication required");
  expect(await prisma.careerProfile.findMany({
    where: { user: { supabaseAuthId: { in: identities } } }, orderBy: { id: "asc" },
  })).toEqual(before);
});

it("does not overwrite edits when provisioning runs again", async () => {
  await saveProfile({}, form("Keep my edits"));
  await ensureCurrentUserProfile();
  expect((await getCurrentProfile())?.displayName).toBe("Keep my edits");
});

it("enforces one profile per user and a valid user foreign key", async () => {
  const user = await prisma.user.findUniqueOrThrow({ where: { supabaseAuthId: accountA } });
  await expect(prisma.careerProfile.create({
    data: { userId: user.id, displayName: "Duplicate" },
  })).rejects.toMatchObject({ code: "P2002" });
  await expect(prisma.careerProfile.create({
    data: { userId: randomUUID(), displayName: "Orphan" },
  })).rejects.toMatchObject({ code: "P2003" });
});
